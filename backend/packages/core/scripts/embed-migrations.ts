/**
 * Build-time codegen: embeds the committed SQL migrations into
 * `src/db/embedded-migrations.generated.ts` so the SEA executable can run
 * migrations with no files on disk (decision D-011).
 *
 * Run via `pnpm --filter @workjournal/core embed` (chained into `build`).
 * Unlike the UI embed, a missing migrations directory is a hard error — those
 * files are committed source, absence means a broken checkout.
 *
 * The output file is COMMITTED for the same reason as the UI embed: a fresh
 * clone must typecheck and build before any codegen has run.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url)); // packages/core/scripts/
const outFile = resolve(here, '../src/db/embedded-migrations.generated.ts');

interface DirSpec {
  /** Exported function name in the generated module. */
  exportName: string;
  dir: string;
}

const specs: DirSpec[] = [
  { exportName: 'embeddedRegistryMigrations', dir: resolve(here, '../migrations') },
  { exportName: 'embeddedProjectMigrations', dir: resolve(here, '../project-migrations') },
];

function readMigrations(dir: string): { name: string; sql: string }[] {
  let names: string[];
  try {
    names = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  } catch (err) {
    throw new Error(
      `embed-migrations: cannot read ${dir} — the committed SQL migrations are required ` +
        `(${err instanceof Error ? err.message : err}).`,
    );
  }
  if (names.length === 0) {
    throw new Error(`embed-migrations: no .sql files in ${dir} — refusing to embed an empty set.`);
  }
  return names.map((name) => ({ name, sql: readFileSync(join(dir, name), 'utf-8') }));
}

const functions = specs
  .map(({ exportName, dir }) => {
    const entries = readMigrations(dir);
    const rows = entries
      .map((e) => `    { name: ${JSON.stringify(e.name)}, sql: ${JSON.stringify(e.sql)} }`)
      .join(',\n');
    return (
      `export function ${exportName}(): MigrationFile[] {\n` +
      `  return [\n${rows},\n  ];\n}`
    );
  })
  .join('\n\n');

const output = `// GENERATED by packages/core/scripts/embed-migrations.ts — do not edit by hand.
// Regenerate with \`pnpm --filter @workjournal/core embed\`. Committed
// intentionally (decision D-011): a fresh clone must typecheck and build
// without running codegen first.
import type { MigrationFile } from './migrate.js';

${functions}
`;

writeFileSync(outFile, output);
const summary = specs
  .map(({ exportName, dir }) => {
    const count = readMigrations(dir).length;
    return `${exportName}=${count} (${relative(resolve(here, '../../../..'), dir)})`;
  })
  .join(', ');
process.stdout.write(`embed-migrations: wrote ${relative(resolve(here, '../../../..'), outFile)} — ${summary}\n`);
