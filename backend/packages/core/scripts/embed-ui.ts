/**
 * Build-time codegen: embeds `frontend/dist` into
 * `src/ui/embedded-ui.generated.ts` so `--with-ui` and the SEA executable can
 * serve the dashboard with no files on disk.
 *
 * Run via `pnpm --filter @workjournal/core embed` (also chained into `build`).
 * When `frontend/dist` has not been built, a `null` set is emitted — the core
 * service then starts API-only, exactly as before. That also keeps the Docker
 * core image (backend-only build context) behaviourally unchanged.
 *
 * The output file is COMMITTED so a fresh clone typechecks and builds without
 * requiring a frontend build first (decision D-011).
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { contentTypeFor } from '../src/ui/content-type.js';

const here = dirname(fileURLToPath(import.meta.url)); // packages/core/scripts/
const distDir = resolve(here, '../../../../frontend/dist');
const outFile = resolve(here, '../src/ui/embedded-ui.generated.ts');

interface Asset {
  contentType: string;
  base64: string;
}

function collect(dir: string): Record<string, Asset> {
  const files: Record<string, Asset> = {};
  const walk = (current: string): void => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const full = join(current, entry.name);
      if (entry.isDirectory()) {
        walk(full);
        continue;
      }
      const rel = relative(dir, full).split(sep).join('/');
      files[rel] = {
        contentType: contentTypeFor(rel),
        base64: readFileSync(full).toString('base64'),
      };
    }
  };
  walk(dir);
  // Deterministic output: sort keys so rebuilds without UI changes are diff-clean.
  return Object.fromEntries(Object.entries(files).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

let embedded: Record<string, Asset> | null = null;
if (existsSync(join(distDir, 'index.html'))) {
  embedded = collect(distDir);
} else {
  process.stderr.write(
    `embed-ui: ${distDir} not found (frontend not built) — emitting null UI assets; ` +
      `the core service will be API-only.\n`,
  );
}

const output = `// GENERATED by packages/core/scripts/embed-ui.ts — do not edit by hand.
// Regenerate with \`pnpm --filter @workjournal/core embed\` after building the
// frontend. Committed intentionally (decision D-011): a fresh clone must
// typecheck and build without a frontend build step.
import type { UiAsset } from './ui-assets.js';

export const embeddedUiFiles: Record<string, UiAsset> | null = ${JSON.stringify(embedded, null, 2)};
`;

writeFileSync(outFile, output);
process.stdout.write(
  `embed-ui: wrote ${relative(resolve(here, '../../../..'), outFile)} ` +
    `(${embedded ? `${Object.keys(embedded).length} files` : 'null — API-only'})\n`,
);
